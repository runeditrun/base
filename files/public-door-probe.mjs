import assert from 'node:assert/strict';
import { writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const base = process.argv[2], packet = process.argv[3];
const {fixture} = await import(pathToFileURL(join(base,'cli/fixtures/reference.mjs')));
const { productionSender } = await import(pathToFileURL(join(base,'cli/fixtures/production-sender.mjs')));
const cleanup = [], rows = [];
const t = {after:fn=>cleanup.push(fn), diagnostic:()=>{}};
const f = await fixture('foundation',t);
try {
 await f.documented('pnpm install --frozen-lockfile');
 const path=join(f.root,'deploy.json'), original=await readFile(path,'utf8'), declaration=JSON.parse(original);
 const envFile='.rer/public-door/inputs.env';
 const { mkdir } = await import('node:fs/promises');
 await mkdir(join(f.root,'.rer/public-door'),{recursive:true});
 const run=async(label,values,expected,{dry=true}={})=>{
  await writeFile(join(f.root,envFile),values,{mode:0o600});
  const args=['deploy',...(dry?['--dry-run']:[]),'--env-file',envFile,'--owner-name','Morgan Ellis','--non-interactive','--json'];
  const child=f.start(args),code=await child.done;
  const events=child.stdoutText.trim().split('\n').filter(Boolean).map(line=>{try{return JSON.parse(line)}catch{return null}}).filter(Boolean);
  const row={label,command:'node scripts/rer.mjs '+args.join(' '),exit:code,errors:events.filter(e=>e.event==='error').map(({code,message})=>({code,message})),result:events.findLast(e=>e.event==='result'),providerCredentialsSupplied:false};
  rows.push(row);
  await writeFile(join(packet,'public-door-receipt.json'),JSON.stringify({source:process.env.PROBE_SOURCE_SHA,stamp:new Date().toISOString(),rows},null,2)+'\n');
  console.log(label,JSON.stringify(row));
  assert.equal(code,expected,JSON.stringify(row));
  return row;
 };
 declaration.vars.MAIL_FROM=productionSender;
 await writeFile(path,JSON.stringify(declaration));
 const before=await run('before-unchanged-journey','MAIL_API_KEY=test-only-outbound-key\n',1);
 assert.match(before.errors[0].message,/invalid-public-variable/);
 assert.match(before.errors[0].message,/Resources created this attempt: none/);
 await writeFile(path,original);
 const after=await run('after-declared-sender-input',`MAIL_API_KEY=test-only-outbound-key\nMAIL_FROM=${productionSender}\n`,0);
 assert.equal(after.result.ok,true);
 assert.equal(after.result.plan.d1[0].binding,'DB');
 assert.ok(after.result.plan.secrets.some(e=>e.binding==='MAIL_FROM'));
 assert.ok(!after.result.plan.vars.includes('MAIL_FROM'));
 const none=await run('explicit-mail-off','MAIL_PROVIDER=none\n',0);
 assert.ok(none.result.plan.secrets.some(e=>e.binding==='MAIL_PROVIDER'));
 assert.ok(!none.result.plan.vars.includes('MAIL_PROVIDER'));
 const missing=await run('enabled-provider-missing-credential',`MAIL_PROVIDER=resend\nMAIL_FROM=${productionSender}\n`,4,{dry:false});
 assert.match(missing.errors[0].message,/Production sign-in is not configured/);
 const conflict=await run('mail-off-with-credential','MAIL_PROVIDER=none\nMAIL_API_KEY=synthetic-conflicting-credential\n',4,{dry:false});
 assert.match(conflict.errors[0].message,/turns outbound email off/);
 declaration.vars={...declaration.vars,PUBLIC_NUMBER:42};
 await writeFile(path,JSON.stringify(declaration));
 const invalid=await run('invalid-public-variable-still-refused','MAIL_PROVIDER=none\n',1);
 assert.match(invalid.errors[0].message,/invalid-public-variable/);
} finally {for(const fn of cleanup.reverse())await fn();}
