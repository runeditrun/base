import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync, spawnSync} from 'node:child_process';

const cli = new URL('./cli.mjs', import.meta.url);
const git = (root, ...args) => execFileSync('git', ['-C', root, ...args], {encoding: 'utf8', stdio: 'pipe'}).trim();
function write(root, name, bytes) {
  fs.mkdirSync(path.dirname(path.join(root, name)), {recursive: true});
  fs.writeFileSync(path.join(root, name), bytes);
}
function commit(root) {
  git(root, 'add', '-A'); git(root, 'commit', '-qm', 'fixture'); return git(root, 'rev-parse', 'HEAD');
}
function run(root, ...args) {
  const result = spawnSync(process.execPath, [cli.pathname, ...args], {cwd: root, encoding: 'utf8'});
  return {...result, report: result.stdout && JSON.parse(result.stdout)};
}
function ok(root, ...args) {
  const result = run(root, ...args);
  assert.equal(result.status, 0, result.stderr); return result.report;
}
function fixture(fn) {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'refresh-packages-'));
  const base = path.join(temp, 'base'), seed = path.join(temp, 'seed');
  try {
    for (const root of [base, seed]) {
      fs.mkdirSync(root); git(root, 'init', '-q');
      git(root, 'config', 'user.name', 'Test'); git(root, 'config', 'user.email', 'test@example.invalid');
    }
    write(base, 'default-seed/package.json', JSON.stringify({dependencies: {'drizzle-orm': '0.45.4'}}));
    write(base, 'default-seed/src/core/native.ts', 'export const storage = "D1";\n');
    write(seed, 'src/core/native.ts', 'export const storage = "D1";\n');
    write(seed, 'package.json', JSON.stringify({type: 'module', dependencies: {}}));
    const pin = commit(base);
    ok(seed, 'record-base', 'src/core', 'default-seed/src/core', pin, '--base', base);
    commit(seed);
    write(base, 'default-seed/src/core/native.ts', 'export const storage = "native D1";\n');
    write(base, 'default-seed/src/core/reference/repository.ts', "import {sql} from 'drizzle-orm';\nexport const query = sql`select 1`;\n");
    write(base, 'default-seed/src/core/reference/schema.ts', "export {sqliteTable} from 'drizzle-orm/sqlite-core';\n");
    write(base, 'default-seed/src/core/reference/types.ts', "export type Database = typeof import('drizzle-orm/d1');\n");
    write(base, 'default-seed/src/core/reference/service.ts', "export {query} from './repository';\nexport {sqliteTable} from './schema';\nexport type {Database} from './types';\n");
    write(base, 'default-seed/src/core/records.ts', "export * from './reference/service';\n");
    fn({base, seed, next: () => commit(base)});
  } finally { fs.rmSync(temp, {recursive: true, force: true}); }
}

test('refresh-base withholds undeclared optional package modules and leaves generated workflow inputs to the seed', () => {
  fixture(({base, seed, next}) => {
    // A packaging input is generated by the seed, not a request for Base's routes.
    write(seed, '.github/workflows/verify.yml', 'jobs:\n  build:\n    steps:\n      - run: tar -czf build.tar.gz src/routeTree.gen.ts\n');
    write(base, 'default-seed/src/routeTree.gen.ts', "export * from './core/records';\n");
    commit(seed);
    const revision = next(), manifest = fs.readFileSync(path.join(seed, 'package.json'));
    const report = ok(seed, 'refresh-base', revision, '--base', base);
    assert.equal(fs.existsSync(path.join(seed, 'src/routeTree.gen.ts')), false);
    assert.equal(fs.existsSync(path.join(seed, 'src/core/reference')), false);
    assert.equal(fs.existsSync(path.join(seed, 'src/core/records.ts')), false);
    assert.match(fs.readFileSync(path.join(seed, 'src/core/native.ts'), 'utf8'), /native D1/);
    assert.ok(report.withheld.some(item => item.package === 'drizzle-orm'));
    assert.deepEqual(fs.readFileSync(path.join(seed, 'package.json')), manifest);
    commit(seed);
    assert.equal(ok(seed, 'verify-base', '--base', base).ok, true);
    assert.deepEqual(ok(seed, 'refresh-base', revision, '--base', base).withheld, []);
  });
});

test('refresh-base refuses required missing packages, reports existing versions, and protects seed edits', () => {
  fixture(({base, seed, next}) => {
    write(base, 'default-seed/src/core/native.ts', "export {query} from './reference/repository';\n");
    const revision = next(), before = fs.readFileSync(path.join(seed, 'base-copies.json'));
    const refused = run(seed, 'refresh-base', revision, '--base', base);
    assert.equal(refused.status, 1);
    assert.match(refused.stderr, /drizzle-orm/);
    assert.deepEqual(fs.readFileSync(path.join(seed, 'base-copies.json')), before);
    assert.equal(fs.existsSync(path.join(seed, 'src/core/reference')), false);
    // Declared versions belong to the seed, even when Base uses another version.
    const manifest = JSON.stringify({type: 'module', dependencies: {'drizzle-orm': '^0.45.2'}});
    write(seed, 'package.json', manifest);
    const report = ok(seed, 'refresh-base', revision, '--base', base);
    assert.ok(report.packageDependencies.some(item => item.package === 'drizzle-orm' && item.conflict));
    assert.equal(fs.readFileSync(path.join(seed, 'package.json'), 'utf8'), manifest);
    commit(seed);
    write(seed, 'src/core/reference/repository.ts', 'export const query = "seed edit";\n');
    const edited = run(seed, 'refresh-base', revision, '--base', base);
    assert.equal(edited.status, 1);
    assert.match(edited.stderr, /local edits/);
    assert.equal(fs.readFileSync(path.join(seed, 'src/core/reference/repository.ts'), 'utf8'), 'export const query = "seed edit";\n');
  });
});
