import { checkCases } from '../onboarding/test-fixture.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, writeFile, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const helper = fileURLToPath(new URL('./publish.mjs', import.meta.url));
async function fixture(t, familyId = 'support', edition = 'lily') {
  const root = await mkdtemp(resolve(tmpdir(), 'base-publish-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const env = { ...process.env, GIT_CONFIG_GLOBAL: resolve(root, 'gitconfig'), GIT_CONFIG_NOSYSTEM: '1' };
  const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], { env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  const family = resolve(root, 'family');
  const target = resolve(root, 'target');
  const source = resolve(root, 'source');
  await writeFile(env.GIT_CONFIG_GLOBAL, '[user]\nname = Test\nemail = test@example.invalid\n');
  for (const dir of [family, target, source]) await mkdir(dir);
  for (const name of [familyId, `${familyId}-${edition}`]) {
    const remote = resolve(root, `${name}.git`);
    git(root, 'init', '--bare', '--initial-branch=main', remote);
    git(root, 'config', '--global', `url.${remote}.insteadOf`, `https://github.com/runeditrun/${name}.git`);
  }
  for (const [dir, name] of [[family, familyId], [target, `${familyId}-${edition}`]]) {
    git(dir, 'init', '--initial-branch=main');
    git(dir, 'remote', 'add', 'origin', `https://github.com/runeditrun/${name}.git`);
  }
  const base = { repository: 'runeditrun/base', commit: 'a'.repeat(40) };
  await writeFile(resolve(family, 'family.json'), JSON.stringify({ schemaVersion: 1, id: familyId, repository: `runeditrun/${familyId}`, base }));
  await writeFile(resolve(family, 'publication.json'), JSON.stringify({ schemaVersion: 1, family: `runeditrun/${familyId}`, editions: { [edition]: `runeditrun/${familyId}-${edition}` } }));
  git(family, 'add', '.');
  async function advance() {
    git(family, 'commit', '--allow-empty', '-m', 'family revision');
    git(family, 'push', 'origin', 'main');
    return git(family, 'rev-parse', 'HEAD');
  }
  const sha = await advance();
  async function generate(commit = sha, content = 'hello') {
    await rm(source, { recursive: true });
    await mkdir(resolve(source, '.github'), { recursive: true });
    const entries = { '.gitignore': 'ignored.txt\n', 'ignored.txt': content, '.github/example.yml': 'name: example\n' };
    const files = {};
    for (const [name, bytes] of Object.entries(entries)) {
      await writeFile(resolve(source, name), bytes);
      files[name] = { sha256: createHash('sha256').update(bytes).digest('hex'), mode: 0o644 };
    }
    await writeFile(resolve(source, 'composition.lock.json'), JSON.stringify({ schemaVersion: 2, composition: { edition }, repositories: { base, family: { repository: `runeditrun/${familyId}`, commit } }, files }));
  }
  await generate();
  const run = (...extra) => execFileSync(process.execPath, [helper, '--source', source, '--target', target, '--family', family, '--sha', sha, '--edition', edition, ...extra], { env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  return { root, family, target, source, sha, git, run, advance, generate };
}

test("publication preserves generated bytes and history through preflight, explicit mappings and no-op repeats", () => checkCases([
  ['preflight is read-only; publishing keeps ignored dotfiles and history; repeat is no-op', async t => {
  const f = await fixture(t);
  assert.deepEqual(JSON.parse(f.run('--check')), { checked: true });
  assert.equal(f.git(f.target, 'ls-files'), '');
  f.git(f.root, 'config', '--global', '--unset', 'user.name');
  f.git(f.root, 'config', '--global', '--unset', 'user.email');
  assert.equal(JSON.parse(f.run()).changed, true);
  assert.equal(f.git(f.target, 'log', '-1', '--format=%an'), 'github-actions[bot]');
  assert.match(f.git(f.target, 'ls-files'), /\.github\/example.yml/);
  assert.match(f.git(f.target, 'ls-files'), /ignored.txt/);
  assert.equal(JSON.parse(f.run()).changed, false);
  const initial = f.git(f.target, 'rev-parse', 'HEAD');
  await f.generate(f.sha, 'updated');
  f.run();
  assert.equal(f.git(f.target, 'rev-parse', 'HEAD^'), initial);
}],
  ['Sales editions and additional Support IDs use explicit committed mappings', async t => {
  for (const [family, edition] of [['sales', 'ferry'], ['sales', 'orbit'], ['support', 'dispatch']]) {
    const f = await fixture(t, family, edition);
    assert.equal(JSON.parse(f.run()).changed, true);
    assert.equal(JSON.parse(f.run()).changed, false);
    assert.match(f.git(f.target, 'log', '-1', '--format=%s'), new RegExp(`from ${family}`));
  }
}]
]));

test("publication target custody refuses tampered bytes, owner customization, races and unrelated history", () => checkCases([
  ['rejects changed generated bytes before changing upstream', async t => {
  const f = await fixture(t);
  await writeFile(resolve(f.source, 'ignored.txt'), 'tampered');
  assert.throws(() => f.run(), /Tree differs from composition lock/);
  assert.equal(f.git(f.target, 'ls-remote', 'origin'), '');
}],
  ['rejects committed target customization and extra tracked files', async t => {
  const f = await fixture(t);
  f.run();
  await writeFile(resolve(f.target, 'custom.txt'), 'owner change');
  f.git(f.target, 'add', 'custom.txt');
  f.git(f.target, 'commit', '-m', 'customize');
  f.git(f.target, 'push', 'origin', 'main');
  assert.throws(() => f.run(), /Tree differs from composition lock file inventory/);
  assert.equal(await readFile(resolve(f.target, 'custom.txt'), 'utf8'), 'owner change');
}],
  ['target race before push is detected without replacing remote history', async t => {
  const f = await fixture(t);
  f.run();
  const first = f.git(f.target, 'rev-parse', 'HEAD');
  const remote = resolve(f.root, 'support-lily.git');
  const concurrent = f.git(f.root, '--git-dir', remote, 'commit-tree', 'main^{tree}', '-p', first, '-m', 'concurrent publication');
  const hook = resolve(f.target, '.git/hooks/pre-commit');
  await writeFile(hook, `#!/bin/sh\ngit --git-dir='${remote}' update-ref refs/heads/main ${concurrent} ${first}\n`, { mode: 0o755 });
  await f.generate(f.sha, 'next publication');
  assert.throws(() => f.run(), /Target main advanced/);
  assert.equal(f.git(f.root, '--git-dir', remote, 'rev-parse', 'main'), concurrent);
}],
  ['an unrelated family history cannot replace an existing generated edition', async t => {
  const f = await fixture(t);
  f.run();
  const published = f.git(f.target, 'rev-parse', 'HEAD');
  const unrelated = f.git(f.family, 'commit-tree', 'HEAD^{tree}', '-m', 'unrelated history');
  f.git(f.family, 'push', '--force', 'origin', `${unrelated}:main`);
  await f.generate(unrelated);
  assert.throws(() => f.run('--sha', unrelated), /merge-base --is-ancestor/);
  assert.equal(f.git(f.target, 'rev-parse', 'HEAD'), published);
}]
]));



test("publication selection identity refuses stale provenance, redirected mappings and wrong destinations", () => checkCases([
  ['rejects stale family main and wrong target origin', async t => {
  const f = await fixture(t);
  await f.advance();
  assert.throws(() => f.run(), /Family main advanced/);
  f.git(f.target, 'remote', 'set-url', 'origin', 'https://github.com/just-every/run-orbit.git');
  assert.throws(() => f.run(), /Origin must be runeditrun\/support-lily/);
}],
  ['rejects target moving after checkout and mismatched source identity', async t => {
  const f = await fixture(t);
  f.run();
  f.git(f.target, 'commit', '--allow-empty', '-m', 'unpublished');
  assert.throws(() => f.run(), /Target HEAD is not current upstream main/);
  const lockPath = resolve(f.source, 'composition.lock.json');
  const lock = JSON.parse(await readFile(lockPath, 'utf8'));
  lock.composition.edition = 'beacon';
  await writeFile(lockPath, JSON.stringify(lock));
  assert.throws(() => f.run(), /Invalid composition lock identity/);
}],
  ['accepts canonical push URL and rejects a different push destination', async t => {
  const f = await fixture(t);
  f.git(f.target, 'config', 'remote.origin.pushurl', f.git(f.target, 'config', '--get', 'remote.origin.url'));
  assert.deepEqual(JSON.parse(f.run('--check')), { checked: true });
  f.git(f.target, 'config', 'remote.origin.pushurl', 'https://github.com/just-every/run-orbit.git');
  assert.throws(() => f.run(), /Unexpected push URL/);
}],
  ['working-tree mapping cannot redirect publication; committed fork mapping is rejected', async t => {
  const f = await fixture(t);
  const path = resolve(f.family, 'publication.json');
  const mapping = JSON.parse(await readFile(path, 'utf8'));
  mapping.editions.lily = 'just-every/run-orbit';
  await writeFile(path, JSON.stringify(mapping));
  assert.deepEqual(JSON.parse(f.run('--check')), { checked: true });
  f.git(f.family, 'add', 'publication.json');
  const next = await f.advance();
  await f.generate(next);
  assert.throws(() => f.run('--sha', next), /distinct canonical repositories/);
}],
  ['rejects wrong Base provenance and untracked ignored owner files', async t => {
  const f = await fixture(t);
  f.run();
  await writeFile(resolve(f.target, '.gitignore'), 'ignored.txt\nowner-secret.txt\n');
  // Even files hidden by .git/info/exclude must survive a rejected publication.
  f.git(f.target, 'checkout', '--', '.gitignore');
  await writeFile(resolve(f.target, '.git/info/exclude'), 'owner-secret.txt\n');
  await writeFile(resolve(f.target, 'owner-secret.txt'), 'private owner bytes');
  assert.throws(() => f.run(), /Target checkout is dirty/);
  assert.equal(await readFile(resolve(f.target, 'owner-secret.txt'), 'utf8'), 'private owner bytes');
  await rm(resolve(f.target, 'owner-secret.txt'));
  const path = resolve(f.source, 'composition.lock.json');
  const lock = JSON.parse(await readFile(path, 'utf8'));
  lock.repositories.base.commit = 'b'.repeat(40);
  await writeFile(path, JSON.stringify(lock));
  assert.throws(() => f.run(), /Invalid composition lock identity/);
}],
  ['committed duplicate destinations are rejected', async t => {
  const f = await fixture(t);
  const path = resolve(f.family, 'publication.json');
  const mapping = JSON.parse(await readFile(path, 'utf8'));
  mapping.editions.beacon = mapping.editions.lily;
  await writeFile(path, JSON.stringify(mapping));
  f.git(f.family, 'add', 'publication.json');
  const next = await f.advance();
  await f.generate(next);
  assert.throws(() => f.run('--sha', next), /distinct canonical repositories/);
}]
]));
